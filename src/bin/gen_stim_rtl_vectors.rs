//! Stim DEM + shots → software cosim gate + RTL goldens (M20/M22).
//!
//! M22: no E≤64 packed-mask limit — emit per-edge solid/corr expectation tasks
//! (Docs/Rtl_Scale_Research option B).
//! M28: goldens via shared `load_stim_rtl_bundle`.

use std::env;
use std::fs;
use std::io::Write;
use std::path::PathBuf;
use std::process::ExitCode;

use aether_decoders::load_stim_rtl_bundle;

fn main() -> ExitCode {
    let mut args = env::args().skip(1);
    let Some(dem_path) = args.next() else {
        eprintln!("usage: gen_stim_rtl_vectors <dem.json> <shots.txt> <out.sv> [max_rtl_cases]");
        return ExitCode::from(2);
    };
    let Some(shots_path) = args.next() else {
        eprintln!("missing shots.txt");
        return ExitCode::from(2);
    };
    let Some(out_path) = args.next() else {
        eprintln!("missing out.sv");
        return ExitCode::from(2);
    };
    let max_rtl: usize = args
        .next()
        .and_then(|s| s.parse().ok())
        .unwrap_or(8);

    let bundle = match load_stim_rtl_bundle(
        PathBuf::from(&dem_path).as_path(),
        PathBuf::from(&shots_path).as_path(),
        max_rtl,
    ) {
        Ok(b) => b,
        Err(e) => {
            eprintln!("{e}");
            return ExitCode::from(1);
        }
    };

    let n = bundle.n as usize;
    let m = bundle.m as usize;
    let out = PathBuf::from(&out_path);
    if let Some(parent) = out.parent() {
        fs::create_dir_all(parent).ok();
    }
    let mut f = fs::File::create(&out).unwrap();
    writeln!(f, "// Auto-generated by gen_stim_rtl_vectors — do not edit.").unwrap();
    writeln!(
        f,
        "// Graph from {}; {} shots cosim-OK ({} nontrivial); {} RTL cases. Per-edge goldens (M22).",
        dem_path,
        bundle.shots_checked,
        bundle.nontrivial,
        bundle.cases.len()
    )
    .unwrap();
    writeln!(f, "`ifndef STIM_CASES_SV").unwrap();
    writeln!(f, "`define STIM_CASES_SV").unwrap();
    writeln!(f, "localparam int STIM_N = {n};").unwrap();
    writeln!(f, "localparam int STIM_M = {m};").unwrap();
    writeln!(f, "localparam int STIM_NUM_OBS = {};", bundle.num_observables).unwrap();
    writeln!(f, "localparam int STIM_NUM_CASES = {};", bundle.cases.len()).unwrap();
    writeln!(f).unwrap();

    writeln!(f, "task automatic load_stim_graph;").unwrap();
    writeln!(f, "  begin").unwrap();
    for v in 0..n {
        let b = if bundle.is_boundary[v] != 0 { 1 } else { 0 };
        writeln!(f, "    bnd_mem[{v}] = 8'd{b};").unwrap();
    }
    for e in 0..m {
        writeln!(f, "    eu_mem[{e}] = 16'd{};", bundle.eu[e]).unwrap();
        writeln!(f, "    ev_mem[{e}] = 16'd{};", bundle.ev[e]).unwrap();
        writeln!(f, "    cap_mem[{e}] = 16'd{};", bundle.cap[e]).unwrap();
    }
    writeln!(f, "`ifdef STIM_WITH_OBS").unwrap();
    for e in 0..m {
        writeln!(f, "    obs_mask_mem[{e}] = 64'h{:016x};", bundle.obs_mask[e]).unwrap();
    }
    writeln!(f, "`endif").unwrap();
    writeln!(f, "  end").unwrap();
    writeln!(f, "endtask").unwrap();
    writeln!(f).unwrap();

    for (i, case) in bundle.cases.iter().enumerate() {
        writeln!(f, "localparam int C{i}_CYCLES = {};", case.cycles).unwrap();
        writeln!(f, "localparam int C{i}_PEEL_OPS = {};", case.peel_ops).unwrap();
        writeln!(f, "localparam [63:0] C{i}_OBS = 64'h{:016x};", case.obs).unwrap();
        writeln!(f, "task automatic load_stim_shot_{i};").unwrap();
        writeln!(f, "  begin").unwrap();
        for (v, &s) in case.syndrome.iter().enumerate() {
            writeln!(f, "    syn_mem[{v}] = 8'd{s};").unwrap();
        }
        writeln!(f, "  end").unwrap();
        writeln!(f, "endtask").unwrap();
        writeln!(f, "task automatic load_exp_{i};").unwrap();
        writeln!(f, "  begin").unwrap();
        for (e, &s) in case.solid.iter().enumerate() {
            let b = if s { 1 } else { 0 };
            writeln!(f, "    exp_solid[{e}] = 1'b{b};").unwrap();
        }
        for (e, &c) in case.corr.iter().enumerate() {
            let b = if c { 1 } else { 0 };
            writeln!(f, "    exp_corr[{e}] = 1'b{b};").unwrap();
        }
        writeln!(f, "  end").unwrap();
        writeln!(f, "endtask").unwrap();
        writeln!(f).unwrap();
    }

    let run_path = out.with_file_name("stim_run.sv");
    let mut rf = fs::File::create(&run_path).unwrap();
    writeln!(rf, "// Auto-generated run body — do not edit.").unwrap();
    for i in 0..bundle.cases.len() {
        writeln!(
            rf,
            "clear_syn(); load_stim_shot_{i}(); load_exp_{i}(); run_shot(C{i}_CYCLES, C{i}_PEEL_OPS);"
        )
        .unwrap();
    }

    writeln!(f, "`endif").unwrap();

    println!(
        "cosim OK: {} shots ({} nontrivial); V={n} E={m}; wrote {} RTL cases → {} (+ {})",
        bundle.shots_checked,
        bundle.nontrivial,
        bundle.cases.len(),
        out.display(),
        run_path.display()
    );
    ExitCode::SUCCESS
}
