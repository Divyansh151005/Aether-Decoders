//! Emit Blueprint golden vectors for grow/merge + peel RTL co-sim (M18/M19).
//!
//! Writes `rtl/gen/blueprint_cases.sv` (Icarus-friendly: no unpacked array params).
//! Golden: `helios_pe` solids/cycles + `decode_cosim` correction mask / peel_ops.

use std::fs;
use std::io::Write;
use std::path::PathBuf;

use aether_decoders::{blueprint_cases, blueprint_golden};

fn main() {
    let out_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("rtl/gen");
    fs::create_dir_all(&out_dir).expect("mkdir rtl/gen");
    let path = out_dir.join("blueprint_cases.sv");
    let mut f = fs::File::create(&path).expect("create sv");

    let cases = blueprint_cases();
    writeln!(f, "// Auto-generated by gen_rtl_vectors — do not edit.").unwrap();
    writeln!(
        f,
        "// Golden: helios_pe solids/cycles + decode_cosim corr/peel_ops."
    )
    .unwrap();
    writeln!(f, "`ifndef BLUEPRINT_CASES_SV").unwrap();
    writeln!(f, "`define BLUEPRINT_CASES_SV").unwrap();
    writeln!(f, "localparam int NUM_CASES = {};", cases.len()).unwrap();
    writeln!(f).unwrap();

    for (i, c) in cases.iter().enumerate() {
        let gld = blueprint_golden(i).unwrap_or_else(|| panic!("missing golden {i}"));
        writeln!(f, "// ---- {} ----", c.name).unwrap();
        writeln!(f, "localparam int C{i}_N = {};", gld.n).unwrap();
        writeln!(f, "localparam int C{i}_M = {};", gld.m).unwrap();
        writeln!(f, "localparam int C{i}_CYCLES = {};", gld.cycles).unwrap();
        writeln!(f, "localparam int C{i}_SOLID = {};", gld.solid_mask).unwrap();
        writeln!(f, "localparam int C{i}_CORR = {};", gld.corr_mask).unwrap();
        writeln!(f, "localparam int C{i}_PEEL_OPS = {};", gld.peel_ops).unwrap();
        writeln!(f, "task automatic load_case_{i};").unwrap();
        writeln!(f, "  begin").unwrap();
        for (j, &s) in c.syndrome.iter().enumerate() {
            writeln!(f, "    syn_mem[{j}] = 8'd{s};").unwrap();
        }
        for (j, &b) in c.is_boundary.iter().enumerate() {
            writeln!(f, "    bnd_mem[{j}] = 8'd{b};").unwrap();
        }
        for (j, &(u, v, cap)) in c.edges.iter().enumerate() {
            writeln!(f, "    eu_mem[{j}] = 8'd{u};").unwrap();
            writeln!(f, "    ev_mem[{j}] = 8'd{v};").unwrap();
            writeln!(f, "    cap_mem[{j}] = 16'd{cap};").unwrap();
        }
        writeln!(f, "  end").unwrap();
        writeln!(f, "endtask").unwrap();
        writeln!(f).unwrap();
    }
    writeln!(f, "`endif").unwrap();
    println!("wrote {} ({} cases)", path.display(), cases.len());
}
